import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
const api = vi.hoisted(() => ({ listMyTimeSessions: vi.fn() }))
vi.mock('../../api/client', () => ({ timeTrackingApi: api }))
import TimeSessionForm from './TimeSessionForm.vue'
const props = { start: '2026-09-07T13:00:00', end: '2026-09-07T14:00:00', timezone: 'Asia/Shanghai', editing: false, busy: false }
beforeEach(() => { vi.useFakeTimers({ toFake: ['Date'] }); vi.setSystemTime(new Date('2026-09-07T08:00:00Z')); api.listMyTimeSessions.mockResolvedValue({ items: [] }) })
afterEach(() => vi.useRealTimers())
describe('手动计时日历', () => {
  it('从两周展开完整日历，支持闰年二月并禁用未来日期', async () => {
    const wrapper = mount(TimeSessionForm, { props })
    expect(wrapper.findAll('.yp-calendar__grid button')).toHaveLength(14)
    expect(wrapper.get('[aria-label="2026-09-08"]').attributes('disabled')).toBeDefined()
    await wrapper.get('.yp-calendar__expand').trigger('click')
    expect(wrapper.findAll('.yp-calendar__grid button')).toHaveLength(42)
    await wrapper.get('.yp-calendar__title').trigger('click')
    await wrapper.get('[aria-label="上一年"]').trigger('click')
    await wrapper.get('[aria-label="上一年"]').trigger('click')
    await wrapper.findAll('.yp-calendar__months button')[1]!.trigger('click')
    expect(wrapper.get('[aria-label="2024-02-29"]').attributes('disabled')).toBeUndefined()
    await wrapper.get('[aria-label="2024-02-29"]').trigger('click')
    expect(wrapper.emitted('update:start')?.[0]).toEqual(['2024-02-29T13:00:00'])
    expect(wrapper.emitted('update:end')?.[0]).toEqual(['2024-02-29T14:00:00'])
    wrapper.unmount()
  })
  it('选择日期保持跨日时长，预览使用公司时区', async () => {
    const wrapper = mount(TimeSessionForm, { props: { ...props, start: '2026-09-06T23:30:00', end: '2026-09-07T00:30:00' } })
    expect(wrapper.get('output').text()).toBe('01h 00m')
    await wrapper.get('[aria-label="2026-09-05"]').trigger('click')
    expect(wrapper.emitted('update:end')?.[0]).toEqual(['2026-09-06T00:30:00'])
    await wrapper.setProps({ start: '2026-09-06T23:30:00', end: '2026-09-06T00:30:00' })
    expect(wrapper.get('.save-session').attributes('disabled')).toBeDefined()
    wrapper.unmount()
  })
  it('浏览其他月份后收起恢复选中日期的两周视图', async () => {
    const wrapper = mount(TimeSessionForm, { props })
    await wrapper.get('.yp-calendar__expand').trigger('click')
    await wrapper.get('[aria-label="上个月"]').trigger('click')
    await wrapper.get('.yp-calendar__expand').trigger('click')
    expect(wrapper.get('h4').text()).toBe('2026年9月')
    expect(wrapper.get('[aria-label="2026-09-07"]').attributes('aria-pressed')).toBe('true')
    wrapper.unmount()
  })
  it('只有与已有记录重叠时才显示处理方式，默认只填空白', async () => {
    const wrapper = mount(TimeSessionForm, { props: { ...props, workItemId: 'item' } })
    await flushPromises()
    expect(wrapper.find('.overlap-mode').exists()).toBe(false)
    api.listMyTimeSessions.mockResolvedValue({ items: [{ session: { id: 's', workItemId: 'other', projectId: 'p', startedAt: new Date('2026-09-07T05:30:00Z'),
      stoppedAt: new Date('2026-09-07T06:30:00Z'), canEdit: true, etag: '"0"' }, title: '其他工作', itemNo: 'T-9', projectName: '项目', contentColorToken: null }] })
    await wrapper.setProps({ end: '2026-09-07T14:30:00' })
    await flushPromises()
    expect(wrapper.get('.overlap-mode [aria-checked="true"]').text()).toBe('只填空白')
    expect(wrapper.get('.overlap-mode__effect').text()).toContain('补录 30m，跳过已有记录的 1h')
    wrapper.unmount()
  })
})
