import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import test from 'node:test'
import { parse, stringify } from 'yaml'
import { bundleOpenApi, generateOpenApi } from './openapi-bundle.mjs'

function fixture(context) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'yumpoo-openapi-bundle-'))
  context.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const write = (file, value) => {
    const target = path.join(root, 'source', file)
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, stringify(value), 'utf8')
  }
  write('bundle.yaml', { root: 'openapi.yaml', paths: ['paths/z.yaml', 'paths/a.yaml'],
    components: ['components/z.yaml', 'components/a.yaml'] })
  write('openapi.yaml', { openapi: '3.0.3', info: { title: 'fixture', version: '1' }, servers: [],
    tags: [{ name: 'Z' }, { name: 'A' }], components: { securitySchemes: {} } })
  write('paths/z.yaml', { paths: { '/z': { get: { responses: { 200: { $ref: '#/components/responses/Ok' } } } } } })
  write('paths/a.yaml', { paths: { '/a': {} } })
  write('components/z.yaml', { components: { responses: { Ok: { description: 'ok' } }, schemas: { Z: { type: 'string' } } } })
  write('components/a.yaml', { components: { schemas: { A: { type: 'string' } } } })
  return { root, source: path.join(root, 'source'), write }
}

test('bundle follows manifest and section order without rewriting references', context => {
  const { source } = fixture(context)
  const text = bundleOpenApi(source)
  const document = parse(text)
  assert.deepEqual(Object.keys(document), ['openapi', 'info', 'servers', 'tags', 'paths', 'components'])
  assert.deepEqual(Object.keys(document.paths), ['/z', '/a'])
  assert.deepEqual(Object.keys(document.components), ['securitySchemes', 'schemas', 'responses'])
  assert.deepEqual(Object.keys(document.components.schemas), ['Z', 'A'])
  assert.equal(document.paths['/z'].get.responses[200].$ref, '#/components/responses/Ok')
  assert(text.startsWith('# 由 contracts/openapi/yumpoo-v1/ 生成'))
  assert(!text.includes('\r'))
  assert(text.endsWith('\n'))
})

test('bundle rejects duplicate path and component keys', context => {
  const { source, write } = fixture(context)
  write('paths/a.yaml', { paths: { '/z': {} } })
  assert.throws(() => bundleOpenApi(source), /重复键：\/z/u)
  write('paths/a.yaml', { paths: { '/a': {} } })
  write('components/a.yaml', { components: { schemas: { Z: { type: 'number' } } } })
  assert.throws(() => bundleOpenApi(source), /重复键：Z/u)
})

test('bundle rejects unknown top-level keys and unlisted files', context => {
  const { source, write } = fixture(context)
  write('paths/a.yaml', { paths: {}, schemas: {} })
  assert.throws(() => bundleOpenApi(source), /未知键：schemas/u)
  write('paths/a.yaml', { paths: {} })
  write('unlisted.yaml', {})
  assert.throws(() => bundleOpenApi(source), /清单外文件：unlisted.yaml/u)
})

test('--check rejects stale generated bytes and leaves them untouched', context => {
  const { root, source, write } = fixture(context)
  const output = path.join(root, 'generated.yaml')
  generateOpenApi(source, output)
  assert.doesNotThrow(() => generateOpenApi(source, output, true))
  const before = fs.readFileSync(output, 'utf8')
  write('paths/a.yaml', { paths: { '/changed': {} } })
  assert.throws(() => generateOpenApi(source, output, true), /OpenAPI 单文件与分域源不同步，运行 pnpm generate:openapi/u)
  assert.equal(fs.readFileSync(output, 'utf8'), before)
})
